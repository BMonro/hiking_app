    fitness_level = COALESCE(profiles.fitness_level, EXCLUDED.fitness_level),
    preferred_difficulty = COALESCE(profiles.preferred_difficulty, EXCLUDED.preferred_difficulty),
    preferred_duration_h = COALESCE(profiles.preferred_duration_h, EXCLUDED.preferred_duration_h),
